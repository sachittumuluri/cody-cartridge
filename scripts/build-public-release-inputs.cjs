#!/usr/bin/env node

const fs = require("node:fs");
const path = require("node:path");
const { isReleaseStoreEnvValue, isStoreEnvPlaceholder, loadStoreEnv } = require("./store-env.cjs");

const projectRoot = path.resolve(__dirname, "..");
const loadedFiles = loadStoreEnv(projectRoot);
const outputJson = path.join(projectRoot, "app-store-assets", "PUBLIC_RELEASE_INPUTS.json");
const outputMarkdown = path.join(projectRoot, "app-store-assets", "PUBLIC_RELEASE_INPUTS.md");

const requiredFields = [
  {
    id: "public-site-url",
    key: "CODY_SITE_URL",
    label: "Public site origin",
    appStoreUse: "Support URL, Privacy Policy URL, Marketing URL, Accessibility URL",
    validation: "HTTPS URL origin with no placeholder value",
    example: "public HTTPS site origin",
    nextAction: "Publish the generated support/privacy site and set CODY_SITE_URL to that HTTPS origin."
  },
  {
    id: "support-email",
    key: "CODY_SUPPORT_EMAIL",
    label: "Public support email",
    appStoreUse: "Support page, privacy policy, TestFlight feedback email",
    validation: "Deliverable public support email address",
    example: "public support email address",
    nextAction: "Set the support inbox that should appear publicly on support/privacy pages."
  },
  {
    id: "review-contact-name",
    key: "CODY_REVIEW_CONTACT_NAME",
    label: "App Review contact name",
    appStoreUse: "App Store Connect App Review Information",
    validation: "Real non-placeholder contact name",
    example: "Release Contact",
    nextAction: "Set the person Apple should contact if review needs clarification."
  },
  {
    id: "review-contact-email",
    key: "CODY_REVIEW_CONTACT_EMAIL",
    label: "App Review contact email",
    appStoreUse: "App Store Connect App Review Information",
    validation: "Deliverable review contact email address",
    example: "private App Review contact email address",
    nextAction: "Set the private App Review contact email; it will be redacted in generated release artifacts."
  },
  {
    id: "review-contact-phone",
    key: "CODY_REVIEW_CONTACT_PHONE",
    label: "App Review contact phone",
    appStoreUse: "App Store Connect App Review Information",
    validation: "Phone number Apple can call during review",
    example: "review contact phone number",
    nextAction: "Set the private App Review phone number; it will be redacted in generated release artifacts."
  }
];

function readJson(relativePath, fallback = {}) {
  const absolutePath = path.join(projectRoot, relativePath);
  return fs.existsSync(absolutePath) ? JSON.parse(fs.readFileSync(absolutePath, "utf8")) : fallback;
}

function isEmail(value) {
  return /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(String(value ?? ""));
}

function isPhone(value) {
  return /^\+?[0-9][0-9 ().-]{6,}[0-9]$/.test(String(value ?? ""));
}

function stateForValue(key, value) {
  if (!value) {
    return "missing";
  }

  if (isStoreEnvPlaceholder(value)) {
    return "placeholder";
  }

  if (key === "CODY_SITE_URL" && !isReleaseStoreEnvValue(key, value)) {
    return "invalid";
  }

  if ((key === "CODY_SUPPORT_EMAIL" || key === "CODY_REVIEW_CONTACT_EMAIL") && !isEmail(value)) {
    return "invalid";
  }

  if (key === "CODY_REVIEW_CONTACT_NAME" && String(value).trim().length < 2) {
    return "invalid";
  }

  if (key === "CODY_REVIEW_CONTACT_PHONE" && !isPhone(value)) {
    return "invalid";
  }

  return "ready";
}

function relatedBlockersFor(releaseBlockers) {
  return (releaseBlockers.categories ?? [])
    .find((category) => category.id === "public-inputs")
    ?.checks?.filter((check) => check.status === "blocked")
    .map((check) => ({
      id: check.id,
      label: check.label,
      action: check.action,
      evidence: check.evidence
    })) ?? [];
}

function renderMarkdown(inputs) {
  const fieldRows = inputs.fields
    .map((field) => `| \`${field.key}\` | ${field.label} | ${field.status} | ${field.valueState} | ${field.appStoreUse} | ${field.nextAction} |`)
    .join("\n");
  const blockerRows =
    inputs.relatedBlockers.length > 0
      ? inputs.relatedBlockers.map((item) => `- ${item.label}: ${item.action}`).join("\n")
      : "- None";

  return `# Cody Cartridge Public Release Inputs

Generated by \`npm run public-inputs:store\`.

This packet lists the public URL/contact values required before strict App Store preflight. It intentionally records only field status, not raw contact values.

## Summary

- App: ${inputs.app.name}
- Bundle ID: \`${inputs.app.bundleId}\`
- Version: ${inputs.app.version}
- Build version: ${inputs.app.buildVersion}
- Generated: ${inputs.generatedAt}
- Release env source: ${inputs.releaseEnv.loadedFiles.length > 0 ? inputs.releaseEnv.loadedFiles.join(", ") : "not loaded"}
- Release env precedence: ${inputs.releaseEnv.precedence.join(" > ")}
- Required fields: ${inputs.summary.requiredCount}
- Ready fields: ${inputs.summary.readyCount}
- Blocked fields: ${inputs.summary.blockerCount}
- Ready for public-input phase: ${inputs.summary.readyForPublicInputs ? "yes" : "no"}

## Required Values

| Key | Field | Status | Value state | App Store use | Next action |
| --- | --- | --- | --- | --- | --- |
${fieldRows}

## Release Env File

Run:

\`\`\`bash
npm run init:store-env
\`\`\`

Then edit ignored \`app-store-assets/site.env\` with the real values. Keep that file out of the handoff archive and source control, and keep its permissions private with \`chmod 600 app-store-assets/site.env\`.

Shell-provided \`CODY_*\` values override file values. When both env files exist, \`app-store-assets/site.env.local\` overrides \`app-store-assets/site.env\` so a release machine can keep a private local overlay without editing the base template copy.

You can also write the private overlay without manually editing files:

\`\`\`bash
npm run configure:store-env -- --site-url https://your-public-site.example --support-email "<support-email>" --review-name "<review-contact-name>" --review-email "<review-contact-email>" --review-phone "<review-contact-phone>"
\`\`\`

## Validation Commands

${inputs.commands.map((command) => `- \`${command}\``).join("\n")}

## Related Public-Input Blockers

${blockerRows}

## Redaction

- Raw email addresses and phone numbers are not written to this packet.
- The final public URLs/contact values are loaded from ignored \`app-store-assets/site.env\`, \`app-store-assets/site.env.local\`, or shell environment variables.
`;
}

function main() {
  const pkg = readJson("package.json");
  const releaseBlockers = readJson("app-store-assets/RELEASE_BLOCKERS.json", { categories: [] });
  const fields = requiredFields.map((field) => {
    const value = process.env[field.key] ?? "";
    const valueState = stateForValue(field.key, value);

    return {
      ...field,
      status: valueState === "ready" ? "ready" : "blocked",
      valueState,
      source: loadedFiles.length > 0 ? "store-env-file-or-shell" : "shell-or-missing",
      redactedValue: valueState === "ready" ? "configured" : valueState
    };
  });
  const blockedFields = fields.filter((field) => field.status !== "ready");
  const inputs = {
    generatedAt: new Date().toISOString(),
    app: {
      name: pkg.build?.productName ?? pkg.name,
      bundleId: pkg.build?.appId,
      version: pkg.version,
      buildVersion: pkg.build?.buildVersion ?? pkg.version
    },
    releaseEnv: {
      loadedFiles,
      privateFilesExcludedFromHandoff: ["app-store-assets/site.env", "app-store-assets/site.env.local"],
      precedence: ["shell env", "app-store-assets/site.env.local", "app-store-assets/site.env"]
    },
    summary: {
      requiredCount: fields.length,
      readyCount: fields.length - blockedFields.length,
      blockerCount: blockedFields.length,
      readyForPublicInputs: blockedFields.length === 0
    },
    fields,
    relatedBlockers: relatedBlockersFor(releaseBlockers),
    commands: [
      "npm run init:store-env",
      "npm run configure:store-env -- --dry-run --site-url https://your-public-site.example --support-email \"<support-email>\" --review-name \"<review-contact-name>\" --review-email \"<review-contact-email>\" --review-phone \"<review-contact-phone>\"",
      "npm run public-release:store -- --self-test",
      "npm run public-release:store:node -- --self-test",
      "npm run public-release:store -- --dry-run",
      "npm run public-release:store:node -- --dry-run",
      "npm run public-release:store:published:node",
      "npm run public-inputs:store",
      "npm run publish-packet:store",
      "npm run public-host:store",
      "npm run check:published-site -- --strict",
      "npm run check:store-env",
      "npm run site:store && npm run site:archive",
      "npm run packet:store && npm run review-brief:store && npm run copy-map:store",
      "npm run report:store-blockers && npm run public-inputs:store && npm run publish-packet:store && npm run public-host:store"
    ],
    sourceArtifacts: [
      "app-store-assets/site.env.example",
      "app-store-assets/RELEASE_BLOCKERS.json",
      "scripts/refresh-public-release.cjs",
      "scripts/build-public-host-runbook.cjs",
      "scripts/check-store-env.cjs"
    ]
  };

  fs.writeFileSync(outputJson, `${JSON.stringify(inputs, null, 2)}\n`);
  fs.writeFileSync(outputMarkdown, renderMarkdown(inputs));

  console.log(`Built ${path.relative(projectRoot, outputJson)}`);
  console.log(`Built ${path.relative(projectRoot, outputMarkdown)}`);

  if (!inputs.summary.readyForPublicInputs) {
    console.warn(`Public release inputs record ${inputs.summary.blockerCount} blocked field(s).`);
  }
}

main();
