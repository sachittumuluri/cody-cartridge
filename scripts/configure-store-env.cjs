#!/usr/bin/env node

const fs = require("node:fs");
const path = require("node:path");
const { isReleaseStoreEnvValue, parseEnvLine, releaseEnvKeys } = require("./store-env.cjs");

const projectRoot = path.resolve(__dirname, "..");
const allowedTargets = new Set(["app-store-assets/site.env", "app-store-assets/site.env.local"]);
const defaultTarget = "app-store-assets/site.env.local";
const labels = {
  CODY_SITE_URL: "public site URL",
  CODY_SUPPORT_EMAIL: "support email",
  CODY_REVIEW_CONTACT_NAME: "App Review contact name",
  CODY_REVIEW_CONTACT_EMAIL: "App Review contact email",
  CODY_REVIEW_CONTACT_PHONE: "App Review contact phone"
};
const flagToKey = {
  "--site-url": "CODY_SITE_URL",
  "--support-email": "CODY_SUPPORT_EMAIL",
  "--review-name": "CODY_REVIEW_CONTACT_NAME",
  "--review-email": "CODY_REVIEW_CONTACT_EMAIL",
  "--review-phone": "CODY_REVIEW_CONTACT_PHONE"
};

function usage() {
  return `Usage:
  npm run configure:store-env -- \\
    --site-url https://your-site.example \\
    --support-email support@example.com \\
    --review-name "Release Contact" \\
    --review-email review@example.com \\
    --review-phone "+1 555 555 5555"

Options:
  --target app-store-assets/site.env.local  Write target. Defaults to the local overlay.
  --dry-run                                Validate without writing.
  --self-test                              Verify quoting/parsing behavior without writing.

Values can also be provided as CODY_* shell environment variables.`;
}

function fail(message) {
  console.error(`FAIL ${message}`);
  process.exitCode = 1;
}

function parseArgs(argv) {
  const parsed = {
    dryRun: false,
    target: defaultTarget,
    values: {}
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];

    if (arg === "--help" || arg === "-h") {
      console.log(usage());
      process.exit(0);
    }

    if (arg === "--dry-run") {
      parsed.dryRun = true;
      continue;
    }

    if (arg === "--self-test") {
      parsed.selfTest = true;
      continue;
    }

    if (arg === "--target") {
      const value = argv[index + 1];
      index += 1;

      if (!value) {
        throw new Error("--target requires a value.");
      }

      parsed.target = value;
      continue;
    }

    const key = flagToKey[arg];

    if (key) {
      const value = argv[index + 1];
      index += 1;

      if (!value) {
        throw new Error(`${arg} requires a value.`);
      }

      parsed.values[key] = value;
      continue;
    }

    throw new Error(`Unknown option: ${arg}`);
  }

  return parsed;
}

function resolveValues(cliValues) {
  return Object.fromEntries(
    releaseEnvKeys.map((key) => [key, String(cliValues[key] ?? process.env[key] ?? "").trim()])
  );
}

function validateTarget(relativePath) {
  if (!allowedTargets.has(relativePath)) {
    throw new Error(`Target must be one of: ${[...allowedTargets].join(", ")}.`);
  }

  const absolutePath = path.join(projectRoot, relativePath);
  const realDirectory = fs.realpathSync(path.dirname(absolutePath));

  if (!realDirectory.startsWith(projectRoot)) {
    throw new Error("Target must stay inside the project directory.");
  }

  if (fs.existsSync(absolutePath) && fs.lstatSync(absolutePath).isSymbolicLink()) {
    throw new Error(`${relativePath} must not be a symlink.`);
  }

  return absolutePath;
}

function validateValues(values) {
  return releaseEnvKeys.filter((key) => !isReleaseStoreEnvValue(key, values[key]));
}

function quoteEnvValue(value) {
  const rawValue = String(value ?? "").trim();

  if (/[\r\n]/.test(rawValue)) {
    throw new Error("Release env values must stay on one line.");
  }

  return `"${rawValue
    .replace(/\\/g, "\\\\")
    .replace(/"/g, '\\"')
    .replace(/\$/g, "\\$")
    .replace(/`/g, "\\`")}"`;
}

function render(values) {
  const lines = [
    "# Cody Cartridge App Store release environment.",
    "# Generated by npm run configure:store-env.",
    "# This file is ignored and should stay private on the release machine.",
    "",
    "# Final HTTPS origin for the published support/privacy site. No trailing slash.",
    `CODY_SITE_URL=${quoteEnvValue(values.CODY_SITE_URL)}`,
    "",
    "# Public support contact shown on support/privacy pages and in App Store Connect.",
    `CODY_SUPPORT_EMAIL=${quoteEnvValue(values.CODY_SUPPORT_EMAIL)}`,
    "",
    "# App Review contact fields copied into App Store Connect.",
    `CODY_REVIEW_CONTACT_NAME=${quoteEnvValue(values.CODY_REVIEW_CONTACT_NAME)}`,
    `CODY_REVIEW_CONTACT_EMAIL=${quoteEnvValue(values.CODY_REVIEW_CONTACT_EMAIL)}`,
    `CODY_REVIEW_CONTACT_PHONE=${quoteEnvValue(values.CODY_REVIEW_CONTACT_PHONE)}`,
    ""
  ];

  return lines.join("\n");
}

function selfTest() {
  const values = {
    CODY_SITE_URL: "https://release.example",
    CODY_SUPPORT_EMAIL: "support+app@release.example",
    CODY_REVIEW_CONTACT_NAME: 'Release #1 "Ops" $Lead \\ Desk',
    CODY_REVIEW_CONTACT_EMAIL: "review@release.example",
    CODY_REVIEW_CONTACT_PHONE: "+1 (555) 555-5555"
  };
  const rendered = render(values);
  const parsed = Object.fromEntries(
    rendered
      .split(/\r?\n/)
      .map(parseEnvLine)
      .filter(Boolean)
      .map((item) => [item.key, item.value])
  );
  const mismatches = releaseEnvKeys.filter((key) => parsed[key] !== values[key]);

  if (mismatches.length > 0) {
    throw new Error(`Quoted env round trip failed for ${mismatches.join(", ")}.`);
  }

  if (!rendered.includes('CODY_REVIEW_CONTACT_NAME="Release #1 \\"Ops\\" \\$Lead \\\\ Desk"')) {
    throw new Error("Quoted env output did not escape shell-sensitive contact-name characters.");
  }

  const invalidOriginValues = {
    ...values,
    CODY_SITE_URL: "https://release.example/support.html"
  };

  if (!validateValues(invalidOriginValues).includes("CODY_SITE_URL")) {
    throw new Error("Store env configurator accepted a CODY_SITE_URL path; expected an HTTPS origin only.");
  }

  console.log("Store env configurator self-test: quoted values round-trip");
}

function main() {
  let options;

  try {
    options = parseArgs(process.argv.slice(2));
  } catch (error) {
    fail(error instanceof Error ? error.message : String(error));
    console.error(usage());
    return;
  }

  if (options.selfTest) {
    try {
      selfTest();
    } catch (error) {
      fail(error instanceof Error ? error.message : String(error));
    }

    return;
  }

  let targetPath;

  try {
    targetPath = validateTarget(options.target);
  } catch (error) {
    fail(error instanceof Error ? error.message : String(error));
    return;
  }

  const values = resolveValues(options.values);
  const invalidKeys = validateValues(values);

  if (invalidKeys.length > 0) {
    invalidKeys.forEach((key) => fail(`${labels[key]} is missing, placeholder, or invalid (${key}).`));
    console.error("No env file was written.");
    return;
  }

  if (options.dryRun) {
    console.log(`Store env configurator dry-run: ${releaseEnvKeys.length} values valid`);
    console.log(`Target would be ${options.target}`);
    return;
  }

  fs.mkdirSync(path.dirname(targetPath), { recursive: true });
  fs.writeFileSync(targetPath, render(values), { encoding: "utf8", mode: 0o600 });
  fs.chmodSync(targetPath, 0o600);

  console.log(`Wrote ${options.target} with ${releaseEnvKeys.length} validated release values.`);
  console.log("Raw contact values were not printed. Run npm run check:store-env next.");
}

main();
